#!/usr/bin/env python3
"""Rebuild data.js: every valid Wordle guess, ordered by how likely it is
to be an answer.

  python3 tools/build_data.py WORDS.txt COUNT_1W.txt

WORDS.txt     current valid-guess list, one word per line
              (https://github.com/tabatkins/wordle-list, file "words")
COUNT_1W.txt  word<TAB>count frequency table
              (https://norvig.com/ngrams/count_1w.txt)

Order written: the 2,309 classic answers (kept from the existing data.js, in
their original order), then common words by falling frequency, then the rest
alphabetically. Plain plurals in -s are never treated as common, since
Wordle does not use them as answers.
"""
import re, sys, pathlib

COMMON_MIN = 100_000   # about 95% of the classic answers sit above this count
CLASSIC = 2309

root = pathlib.Path(__file__).resolve().parent.parent
old, seen = [], set()
for w in re.findall(r'"([a-z]{5})"', (root / 'data.js').read_text()):
    if w not in seen:
        seen.add(w); old.append(w)
classic = old[:CLASSIC]
words = set(old) | {w.strip() for w in open(sys.argv[1]) if re.fullmatch(r'[a-z]{5}', w.strip())}

freq = {}
for line in open(sys.argv[2]):
    p = line.split('\t')
    if len(p) == 2 and p[0] in words:
        freq[p[0]] = int(p[1])

rest = words - set(classic)
plural = lambda w: w.endswith('s') and not w.endswith('ss')
common = sorted((w for w in rest if freq.get(w, 0) >= COMMON_MIN and not plural(w)), key=lambda w: (-freq[w], w))
rare = sorted(rest - set(common))

out = classic + common + rare
assert len(out) == len(set(out)) == len(words)
body = ',\n'.join(' '.join(f'"{w}",' for w in out[i:i + 12]).rstrip(',') for i in range(0, len(out), 12))
(root / 'data.js').write_text(
    '// Generated by tools/build_data.py. Classic answers, then common words by\n'
    '// frequency, then every other valid guess.\n'
    f'export const ANSWER_COUNT = {len(classic)};\n'
    f'export const COMMON_COUNT = {len(common)};\n'
    f'export const COLLECTION = [\n{body}\n];\n')
print(len(classic), 'classic,', len(common), 'common,', len(rare), 'rare,', len(out), 'total')
